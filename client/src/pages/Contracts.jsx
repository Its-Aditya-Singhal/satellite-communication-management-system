import { useState } from 'react';
import { get, patch, post } from '../api.js';
import { useAuth } from '../auth.jsx';
import { Icon } from '../components/Icon.jsx';
import { Badge, Card, DataTable, ErrorBanner, Field, Loader, Modal, PageHeader, Tabs, useFetch, useFlash } from '../components/ui.jsx';
import { fmtDate, fmtMoney, fmtNum, toLocalDateInput } from '../format.js';

export default function Contracts() {
  const { isStaff } = useAuth();
  const [tab, setTab] = useState('contracts');
  const contracts = useFetch(() => get('/contracts'), []);
  const invoices = useFetch(() => get('/invoices'), []);
  const [modal, setModal] = useState(null);
  const [toast, flash] = useFlash();

  const markPaid = async (i) => {
    try {
      await patch(`/invoices/${i.invoice_id}`, { status: 'paid' });
      flash(`Invoice #${i.invoice_id} marked paid`);
      invoices.reload(true);
    } catch (e) { flash(e.message, 'bad'); }
  };
  const setContractStatus = async (c, status) => {
    if (!window.confirm(`Mark ${c.contract_code} as ${status}?`)) return;
    try {
      await patch(`/contracts/${c.contract_id}`, { status });
      flash(`${c.contract_code} is now ${status}`);
      contracts.reload(true);
    } catch (e) { flash(e.message, 'bad'); }
  };

  return (
    <>
      <PageHeader
        title="Contracts & billing"
        subtitle={isStaff ? 'Service contracts and invoices generated by sp_generate_invoice' : 'Your service contracts and invoices'}
        actions={isStaff && (
          <>
            <button className="btn" onClick={() => setModal('invoice')}>Generate invoice</button>
            <button className="btn btn-primary" onClick={() => setModal('contract')}><Icon name="plus" /> New contract</button>
          </>
        )}
      />
      <Tabs value={tab} onChange={setTab} tabs={[
        { value: 'contracts', label: 'Contracts', count: contracts.data?.length },
        { value: 'invoices', label: 'Invoices', count: invoices.data?.length },
      ]} />
      {tab === 'contracts' && (
        <Card pad={false}>
          <Loader state={contracts}>
            {(rows) => (
              <DataTable rows={rows} rowKey={(r) => r.contract_id} columns={[
                { key: 'contract_code', label: 'Contract', render: (r) => <strong className="mono">{r.contract_code}</strong> },
                ...(isStaff ? [{ key: 'client', label: 'Client' }] : []),
                { key: 'start_date', label: 'Term', render: (r) => <span className="nowrap">{fmtDate(r.start_date)} – {fmtDate(r.end_date)}</span> },
                { key: 'days_remaining', label: 'Days left', align: 'right', render: (r) => (r.days_remaining > 0 ? r.days_remaining : '—') },
                { key: 'rate_per_mhz_hour', label: 'Rate / MHz·h', align: 'right', render: (r) => `$${fmtNum(r.rate_per_mhz_hour, 2)}` },
                { key: 'rate_per_pass_min', label: 'Rate / pass-min', align: 'right', render: (r) => `$${fmtNum(r.rate_per_pass_min, 2)}` },
                { key: 'sessions', label: 'Sessions', align: 'right' },
                { key: 'leased_mhz_now', label: 'Leased now', align: 'right', render: (r) => `${fmtNum(r.leased_mhz_now)} MHz` },
                { key: 'billed', label: 'Billed', align: 'right', render: (r) => fmtMoney(r.billed) },
                { key: 'status', label: 'Status', render: (r) => <Badge value={r.status} /> },
                ...(isStaff ? [{ key: 'x', label: '', nosort: true, render: (r) => r.status === 'active'
                  ? <button className="btn btn-sm btn-danger" onClick={() => setContractStatus(r, 'terminated')}>Terminate</button> : null }] : []),
              ]} />
            )}
          </Loader>
        </Card>
      )}
      {tab === 'invoices' && (
        <Card pad={false}>
          <Loader state={invoices}>
            {(rows) => (
              <DataTable rows={rows} rowKey={(r) => r.invoice_id} columns={[
                { key: 'invoice_id', label: 'Invoice', render: (r) => <span className="mono">INV-{String(r.invoice_id).padStart(5, '0')}</span> },
                ...(isStaff ? [{ key: 'client', label: 'Client' }] : []),
                { key: 'contract_code', label: 'Contract', render: (r) => <span className="mono">{r.contract_code}</span> },
                { key: 'period_start', label: 'Period', render: (r) => <span className="nowrap">{fmtDate(r.period_start)} – {fmtDate(r.period_end)}</span> },
                { key: 'mhz_hours', label: 'MHz·h', align: 'right', render: (r) => fmtNum(r.mhz_hours) },
                { key: 'pass_minutes', label: 'Pass minutes', align: 'right', render: (r) => fmtNum(r.pass_minutes) },
                { key: 'amount', label: 'Amount', align: 'right', render: (r) => <strong>{fmtMoney(r.amount)}</strong> },
                { key: 'status', label: 'Status', render: (r) => <Badge value={r.status} /> },
                ...(isStaff ? [{ key: 'x', label: '', nosort: true, render: (r) => r.status !== 'paid' ? <button className="btn btn-sm" onClick={() => markPaid(r)}>Mark paid</button> : null }] : []),
              ]} />
            )}
          </Loader>
        </Card>
      )}
      {modal === 'contract' && <ContractModal onClose={() => setModal(null)} onDone={() => { setModal(null); flash('Contract created'); contracts.reload(true); }} />}
      {modal === 'invoice' && <InvoiceModal contracts={contracts.data || []} onClose={() => setModal(null)}
                                            onDone={(inv) => { setModal(null); setTab('invoices'); flash(`Invoice #${inv.invoice_id}: ${fmtMoney(inv.amount)}`); invoices.reload(true); contracts.reload(true); }} />}
      {toast}
    </>
  );
}

function ContractModal({ onClose, onDone }) {
  const clients = useFetch(() => get('/clients'), []);
  const today = new Date();
  const [f, setF] = useState({
    client_id: '', start_date: toLocalDateInput(today),
    end_date: toLocalDateInput(new Date(today.getTime() + 365 * 864e5)), rate_per_mhz_hour: 2.5, rate_per_pass_min: 12,
  });
  const [error, setError] = useState(null);
  const set = (k) => (e) => setF((s) => ({ ...s, [k]: e.target.value }));
  const clientId = f.client_id || clients.data?.[0]?.client_id || '';
  const submit = async () => {
    setError(null);
    try { await post('/contracts', { ...f, client_id: clientId }); onDone(); } catch (e) { setError(e); }
  };
  return (
    <Modal title="New contract" onClose={onClose}
           footer={<><button className="btn" onClick={onClose}>Cancel</button><button className="btn btn-primary" onClick={submit}>Create</button></>}>
      {error && <ErrorBanner error={error} />}
      <div className="form-grid">
        <Field label="Client">
          <select value={clientId} onChange={set('client_id')}>{(clients.data || []).map((c) => <option key={c.client_id} value={c.client_id}>{c.name}</option>)}</select>
        </Field>
        <span />
        <Field label="Start date"><input type="date" value={f.start_date} onChange={set('start_date')} /></Field>
        <Field label="End date"><input type="date" value={f.end_date} onChange={set('end_date')} /></Field>
        <Field label="Rate per MHz·hour ($)"><input type="number" step="0.05" value={f.rate_per_mhz_hour} onChange={set('rate_per_mhz_hour')} /></Field>
        <Field label="Rate per pass minute ($)"><input type="number" step="0.5" value={f.rate_per_pass_min} onChange={set('rate_per_pass_min')} /></Field>
      </div>
    </Modal>
  );
}

function InvoiceModal({ contracts, onClose, onDone }) {
  const now = new Date();
  const first = new Date(now.getFullYear(), now.getMonth(), 1);
  const [f, setF] = useState({ contract_id: contracts[0]?.contract_id ?? '', period_start: toLocalDateInput(first), period_end: toLocalDateInput(now) });
  const [error, setError] = useState(null);
  const set = (k) => (e) => setF((s) => ({ ...s, [k]: e.target.value }));
  const submit = async () => {
    setError(null);
    try { onDone(await post('/invoices/generate', f)); } catch (e) { setError(e); }
  };
  return (
    <Modal title="Generate invoice" onClose={onClose}
           footer={<><button className="btn" onClick={onClose}>Cancel</button><button className="btn btn-primary" onClick={submit}>Generate</button></>}>
      {error && <ErrorBanner error={error} />}
      <div className="form-grid">
        <Field label="Contract">
          <select value={f.contract_id} onChange={set('contract_id')}>{contracts.map((c) => <option key={c.contract_id} value={c.contract_id}>{c.contract_code} · {c.client}</option>)}</select>
        </Field>
        <span />
        <Field label="Period start"><input type="date" value={f.period_start} onChange={set('period_start')} /></Field>
        <Field label="Period end (exclusive)"><input type="date" value={f.period_end} onChange={set('period_end')} /></Field>
      </div>
      <p className="muted small" style={{ marginBottom: 0 }}>
        <code>sp_generate_invoice</code> sums leased MHz·hours and session minutes that overlap the period. Re-running the same period updates the existing invoice (upsert on the unique key).
      </p>
    </Modal>
  );
}
